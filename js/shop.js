/* =========================================================
   SHOP PAGE ADD TO CART
========================================================= */

document.addEventListener(
    "click",
    function (event) {

        /* ---------------------------------------------
           Check if ADD TO CART button was clicked
        --------------------------------------------- */

        const button =
            event.target.closest(
                ".add-cart-btn"
            );


        if (!button) {
            return;
        }


        /* ---------------------------------------------
           Prevent any other click behavior
        --------------------------------------------- */

        event.preventDefault();
        event.stopImmediatePropagation();


        /* ---------------------------------------------
           Get product ID from button
        --------------------------------------------- */

        const productId =
            button.getAttribute(
                "data-product-id"
            );


        if (!productId) {

            console.error(
                "Shop Add to Cart: Product ID not found."
            );

            return;
        }


        /* ---------------------------------------------
           Find product from master catalog
        --------------------------------------------- */

        const product =
            products.find(
                function (item) {

                    return String(
                        item.id
                    ) === String(
                        productId
                    );

                }
            );


        if (!product) {

            console.error(
                "Shop Add to Cart: Product not found.",
                productId
            );

            return;
        }


        /* ---------------------------------------------
           Same cart storage used by cart.js
        --------------------------------------------- */

        const CART_KEY =
            "webstore_cart";


        let cart = [];


        try {

            cart =
                JSON.parse(
                    localStorage.getItem(
                        CART_KEY
                    )
                ) || [];


            if (!Array.isArray(cart)) {

                cart = [];

            }

        } catch (error) {

            console.error(
                "Shop Add to Cart: Could not read cart.",
                error
            );

            cart = [];

        }


        /* ---------------------------------------------
           Check whether product already exists
        --------------------------------------------- */

        const existingIndex =
            cart.findIndex(
                function (item) {

                    return String(
                        item.id
                    ) === String(
                        product.id
                    );

                }
            );


        /* ---------------------------------------------
           Product already exists
           Increase quantity
        --------------------------------------------- */

        if (
            existingIndex !== -1
        ) {

            cart[
                existingIndex
            ].quantity =
                Number(
                    cart[
                        existingIndex
                    ].quantity || 1
                ) + 1;

        }


        /* ---------------------------------------------
           Product does not exist
           Add new product
        --------------------------------------------- */

        else {

            cart.push({

                id:
                    product.id,

                title:
                    product.title,

                name:
                    product.title,

                price:
                    Number(
                        product.price
                    ),

                image:
                    product.image ||
                    (
                        product.images &&
                        product.images[0]
                    ) ||
                    "images/logo.png",

                imgSrc:
                    product.image ||
                    (
                        product.images &&
                        product.images[0]
                    ) ||
                    "images/logo.png",

                quantity:
                    1,

                category:
                    product.category

            });

        }


        /* ---------------------------------------------
           Save updated cart
        --------------------------------------------- */

        localStorage.setItem(
            CART_KEY,
            JSON.stringify(cart)
        );


        /* ---------------------------------------------
           Update header cart / mini cart
        --------------------------------------------- */

        if (
            typeof window.updateHeaderCart ===
            "function"
        ) {

            window.updateHeaderCart();

        }


        /* ---------------------------------------------
           Change button temporarily
        --------------------------------------------- */

        const originalText =
            button.textContent;


        button.textContent =
            "ADDED ✓";


        button.classList.add(
            "added"
        );


        /* ---------------------------------------------
           Restore button
        --------------------------------------------- */

        setTimeout(
            function () {

                button.textContent =
                    originalText;

                button.classList.remove(
                    "added"
                );

            },
            1000
        );


        console.log(
            "Shop product added to cart:",
            product.title
        );

    },
    false
);