const PRODUCTS_PER_PAGE = 15;

let activeCategory = "all";

let currentPage = 1;

let currentProducts = [...products];


/* =========================================================
   PRODUCT GRID
========================================================= */

function getProductGrid() {

    return document.getElementById(
        "product-grid"
    );

}


/* =========================================================
   RENDER PRODUCTS
========================================================= */

function renderProducts(items) {

    const grid =
        getProductGrid();


    if (!grid) {
        return;
    }


    grid.innerHTML = "";


    /*
       Calculate pagination
    */

    const totalPages =
        Math.max(
            1,
            Math.ceil(
                items.length /
                PRODUCTS_PER_PAGE
            )
        );


    if (
        currentPage >
        totalPages
    ) {

        currentPage =
            totalPages;

    }


    /*
       Start / End
    */

    const startIndex =
        (currentPage - 1) *
        PRODUCTS_PER_PAGE;


    const endIndex =
        startIndex +
        PRODUCTS_PER_PAGE;


    /*
       Only display 15 products
    */

    const pageProducts =
        items.slice(
            startIndex,
            endIndex
        );


    /*
       Render cards
    */

    pageProducts.forEach(
        function (product) {

            const card =
                document.createElement(
                    "div"
                );


            card.className =
                "product-card";



            card.dataset.id =
                product.id;


            card.innerHTML = `

                ${
                    product.sale
                    ?
                    `
                    <span class="badge-sale">
                        SALE
                    </span>
                    `
                    :
                    ""
                }


                <button
                    type="button"
                    class="fav-btn"
                    title="Add to wishlist"
                >
                    <i
                        class="fa-regular fa-heart"
                    ></i>
                </button>


                <a
    href="product-details.html?id=${product.id}"
    class="product-image-link"
>
    <img
        src="${product.image}"
        alt="${product.title}"
        class="product-img"
        loading="lazy"
        onerror="
            this.onerror=null;
            this.src='images/logo.png';
        "
    >
</a>


                <a
    href="product-details.html?id=${product.id}"
    class="product-title product-details-link"
>
    ${product.title}
</a>


                <div
                    class="price-box"
                >

                    $${product.price.toFixed(2)}

                    ${
                        product.oldPrice
                        ?
                        `
                        <span
                            class="old-price"
                        >
                            $${product.oldPrice.toFixed(2)}
                        </span>
                        `
                        :
                        ""
                    }

                </div>


                <button
                    type="button"
                    class="add-cart-btn"
                    data-product-id="${product.id}"
                >
                    ADD TO CART
                </button>

            `;


            grid.appendChild(card);

        }
    );


    /*
       Results text
    */

    const resultsCount =
        document.getElementById(
            "results-count"
        );


    if (resultsCount) {

        if (items.length === 0) {

            resultsCount.innerText =
                "SHOWING 0 OF 0 RESULTS";

        } else {

            const showingStart =
                startIndex + 1;

            const showingEnd =
                Math.min(
                    endIndex,
                    items.length
                );


            resultsCount.innerText =
                `SHOWING ${showingStart}–${showingEnd} OF ${items.length} RESULTS`;

        }

    }


    /*
       Render page numbers
    */

    renderPagination(
        totalPages
    );


    /*
       Sync wishlist hearts
    */

    if (
        typeof syncWishlistIcons ===
        "function"
    ) {

        syncWishlistIcons();

    }

}


/* =========================================================
   PAGINATION
========================================================= */

function renderPagination(totalPages) {


    let pagination =
        document.querySelector(
            ".pagination"
        );


    if (!pagination) {

        pagination =
            document.querySelector(
                ".shop-pagination"
            );

    }


    if (!pagination) {

        pagination =
            document.querySelector(
                "#pagination"
            );

    }



    if (!pagination) {

        pagination =
            document.createElement(
                "div"
            );


        pagination.className =
            "pagination";


        const grid =
            document.getElementById(
                "product-grid"
            );


        if (grid) {

            grid.insertAdjacentElement(
                "afterend",
                pagination
            );

        }

    }


    pagination.innerHTML = "";


    /*
       Previous button
    */

    const previousButton =
        document.createElement(
            "button"
        );


    previousButton.type =
        "button";


    previousButton.className =
        "page-btn prev-page";


    previousButton.innerHTML =
        "‹";


    previousButton.disabled =
        currentPage === 1;


    previousButton.addEventListener(
        "click",
        function () {

            if (
                currentPage > 1
            ) {

                currentPage--;

                renderProducts(
                    currentProducts
                );

                scrollToProducts();

            }

        }
    );


    pagination.appendChild(
        previousButton
    );


    /*
       Page numbers
    */

    for (
        let page = 1;
        page <= totalPages;
        page++
    ) {

        const button =
            document.createElement(
                "button"
            );


        button.type =
            "button";


        button.className =
            "page-btn";


        button.innerText =
            page;


        if (
            page === currentPage
        ) {

            button.classList.add(
                "active"
            );

        }


        button.addEventListener(
            "click",
            function () {

                currentPage =
                    page;


                renderProducts(
                    currentProducts
                );


                scrollToProducts();

            }
        );


        pagination.appendChild(
            button
        );

    }


    /*
       Next button
    */

    const nextButton =
        document.createElement(
            "button"
        );


    nextButton.type =
        "button";


    nextButton.className =
        "page-btn next-page";


    nextButton.innerHTML =
        "NEXT <i class=\"fas fa-chevron-right\"></i>";


    nextButton.disabled =
        currentPage >= totalPages;


    nextButton.addEventListener(
        "click",
        function () {

            if (
                currentPage <
                totalPages
            ) {

                currentPage++;

                renderProducts(
                    currentProducts
                );

                scrollToProducts();

            }

        }
    );


    pagination.appendChild(
        nextButton
    );

}


/* =========================================================
   SCROLL TO PRODUCTS
========================================================= */

function scrollToProducts() {

    const grid =
        document.getElementById(
            "product-grid"
        );


    if (!grid) {
        return;
    }


    const position =
        grid.getBoundingClientRect()
            .top +
        window.scrollY -
        120;


    window.scrollTo({

        top: position,

        behavior: "smooth"

    });

}


